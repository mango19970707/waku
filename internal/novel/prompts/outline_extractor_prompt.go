2. **完整性保证**
   - 完整大纲要保留原始大纲的所有内容
   - 世界观和修行体系要提取所有相关段落
   - 不要遗漏重要的设定细节

3. **结构化输出**
   - 必须严格按照指定格式输出
   - 使用明确的标记分隔不同部分

